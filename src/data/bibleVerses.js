/**
 * 날짜 기반으로 오늘의 말씀을 반환합니다.
 * 매일 자정에 자동으로 바뀝니다.
 */
export function getTodayVerse() {
  const today = new Date();
  const seed  = today.getFullYear() * 10000 + (today.getMonth() + 1) * 100 + today.getDate();
  return VERSES[seed % VERSES.length];
}
